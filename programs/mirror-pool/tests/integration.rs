#[test]
fn settle_zk_rejects_mutated_public_input() {
    let mut env = Env::new();
    let authority = Pubkey::new_unique();
    env.fund(authority, SOL);
    let pool_start = 5 * SOL + ZK_AMOUNT;
    let pool = build_zk_pool(&mut env, &authority, 10, 2, pool_start);
    let recipient = zk_recipient();
    env.fund(recipient, 0);
    env.warp(80);

    // Flip one byte of the nullifierHash public input; derive the nf PDA from the
    // mutated value so the PDA and actionHash checks pass and we reach the proof.
    let mut mutated = fixture::PUBLIC_INPUTS;
    mutated[1][31] ^= 0x01;
    let nf_pda = env.nf_pda(&pool, ZK_EPOCH, &mutated[1]);
    let ix = env.settle_zk_ix(
        &pool, &authority, &nf_pda, &recipient, ZK_EPOCH, ZK_AMOUNT, &mutated,
    );
    env.process(
        &ix,
        &[Check::err(custom(MirrorPoolError::ProofVerificationFailed))],
    );

    // Fail-closed: no escrow moved, no recipient funding, no nullifier PDA.
    assert_eq!(env.get(&recipient).lamports, 0);
    assert_eq!(env.get(&pool).lamports, pool_start);
    assert_eq!(
        env.get(&nf_pda).owner,
        Pubkey::default(),
        "nullifier PDA must not be created on a rejected proof"
    );
}

