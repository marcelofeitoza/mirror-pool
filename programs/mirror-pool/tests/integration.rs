#[test]
fn settle_happy_path_then_double_settle_fails() {
    let mut env = Env::new();
    let (authority, payer, pool) = init_pool(&mut env, 10, 2, 0);
    let epoch_id = 0u64;
    let epoch_acct = env.epoch_pda(&pool, epoch_id);

    env.warp(3);
    for c in [[1u8; 32], [2u8; 32]] {
        let ix = env.commit_ix(&pool, &epoch_acct, &payer, &c);
        env.process(&ix, &[Check::success()]);
    }

    // Window closed (>= settle_slot(0) = 10), count (2) >= k_floor (2).
    env.warp(12);
    let nfs = [[9u8; 32], [8u8; 32]];
    let nf_pdas: Vec<Pubkey> = nfs
        .iter()
        .map(|nf| env.nf_pda(&pool, epoch_id, nf))
        .collect();
    let ix = env.settle_ix(
        &pool,
        &epoch_acct,
        &authority,
        &nf_pdas,
        &nfs,
        &payer,
        epoch_id,
    );
    env.process(&ix, &[Check::success()]);

    // Epoch is marked settled and each nullifier PDA now exists (spent).
    assert!(epoch::is_settled(&env.get(&epoch_acct).data).unwrap());
    for nf_pda in &nf_pdas {
        let acct = env.get(nf_pda);
        assert_eq!(acct.owner, env.program_id, "nullifier PDA must be created");
        assert_eq!(acct.data.len(), nullifier::LEN);
        assert_eq!(acct.data[0], nullifier::SPENT);
    }

    // Settling the same epoch again must fail closed.
    let ix = env.settle_ix(
        &pool,
        &epoch_acct,
        &authority,
        &nf_pdas,
        &nfs,
        &payer,
        epoch_id,
    );
    env.process(
        &ix,
        &[Check::err(custom(MirrorPoolError::EpochAlreadySettled))],
    );
}

/// Build a program-owned, initialized Pool account directly (bypassing the
/// frontier build-up) whose recent-root ring already contains the committed
/// fixture's root, and fund it with `lamports`. This is the "set the pool's root
/// history to include the fixture's root" step: a real deposit sequence cannot
/// reproduce the fixture's single-leaf tree, so the test injects the snapshot.
fn build_zk_pool(
    env: &mut Env,
    authority: &Pubkey,
    epoch_slots: u64,
    k_floor: u32,
    lamports: u64,
) -> Pubkey {
    let pool = env.pool_pda(authority);
    let (_, bump) = Pubkey::find_program_address(&[POOL_SEED, authority.as_ref()], &env.program_id);
    let empty_root = circuit_empty_root();
    let mut data = vec![0u8; pool::LEN];
    pool::init(
        &mut data,
        epoch_slots,
        k_floor,
        0,
        &authority.to_bytes(),
        bump,
        &empty_root,
    )
    .unwrap();
    // Inject the fixture's root snapshot (public signal [0]) into the ring.
    pool::record_root_history(&mut data, &fixture::PUBLIC_INPUTS[0]).unwrap();
    assert!(
        pool::is_known_root(&data, &fixture::PUBLIC_INPUTS[0]).unwrap(),
        "fixture root must be a known recent root"
    );
    let mut account = Account::new(lamports, pool::LEN, &env.program_id);
    account.data = data;
    env.accounts.insert(pool, account);
    pool
}

#[test]
fn commit_deposit_escrows_and_appends() {
    let mut env = Env::new();
    let (_authority, payer, pool) = init_pool(&mut env, 10, 2, 0);
    let pool_after_init = env.get(&pool).lamports;
    let root0 = pool::current_root(&env.get(&pool).data).unwrap();

    env.warp(3);
    let epoch_id = 0u64;
    let epoch_acct = env.epoch_pda(&pool, epoch_id);
    let amount = 400_000_000u64;
    let commitment = [7u8; 32];
    let ix = env.commit_deposit_ix(&pool, &epoch_acct, &payer, &commitment, amount);
    env.process(&ix, &[Check::success()]);

    let pool_acct = env.get(&pool);
    assert_eq!(pool::commitment_count(&pool_acct.data).unwrap(), 1);
    let root1 = pool::current_root(&pool_acct.data).unwrap();
    assert_ne!(root1, root0, "root must change after a deposit-commit");
    assert!(
        pool::is_known_root(&pool_acct.data, &root1).unwrap(),
        "the new root must be recorded in the recent-root ring"
    );
    assert_eq!(
        pool_acct.lamports,
        pool_after_init + amount,
        "the escrow must land in the pool"
    );
    assert_eq!(epoch::commit_count(&env.get(&epoch_acct).data).unwrap(), 1);
}

