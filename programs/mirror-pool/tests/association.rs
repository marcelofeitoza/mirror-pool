#[test]
fn association_and_plain_settle_share_one_spent_set() {
    // Settling WITH an attestation must burn the nullifier for the plain path
    // too. Otherwise a user could take the escrow twice: once "compliantly" and
    // once not. Both paths derive the nullifier PDA from the same seeds, and this
    // pins it.
    let mut env = Env::new();
    let (authority, pool, _curator, assoc) = setup_associated(&mut env);
    let recipient = zk_recipient();
    env.warp(120);

    let nf = fixture::PUBLIC_INPUTS[1];
    let nf_pda = env.nf_pda(&pool, ZK_EPOCH, &nf);
    let ix = env.settle_assoc_ix(
        &pool,
        &authority,
        &nf_pda,
        &recipient,
        &assoc,
        ZK_EPOCH,
        ZK_AMOUNT,
        &fixture::PUBLIC_INPUTS,
    );
    env.process(&ix, &[Check::success()]);

    // The PLAIN SettleZk path, same epoch + nullifier, must now be blocked. It is
    // stopped at the nullifier check, BEFORE any proof verification, which is the
    // ordering that makes the shared spent-set load-bearing.
    let plain_public: [[u8; 32]; 4] = [
        fixture::PUBLIC_INPUTS[0],
        fixture::PUBLIC_INPUTS[1],
        fixture::PUBLIC_INPUTS[2],
        fixture::PUBLIC_INPUTS[3],
    ];
    let ix = env.settle_zk_ix(
        &pool,
        &authority,
        &nf_pda,
        &recipient,
        ZK_EPOCH,
        ZK_AMOUNT,
        &plain_public,
    );
    env.process(&ix, &[Check::err(custom(MirrorPoolError::NullifierSpent))]);
}

