#[test]
fn association_root_ring_wraps_and_evicts_oldest() {
    let mut env = Env::new();
    let authority = Pubkey::new_unique();
    env.fund(authority, SOL);
    let payer = Pubkey::new_unique();
    env.fund(payer, 10 * SOL);
    let pool = build_zk_pool(&mut env, &authority, 10, 5 * SOL);
    let curator = Pubkey::new_unique();
    env.fund(curator, SOL);
    let assoc = register_curator(&mut env, &pool, &curator, &payer);

    let ring = association::ROOT_HISTORY_SIZE;
    let root_at = |i: usize| -> [u8; 32] {
        let mut r = [0u8; 32];
        r[0] = 0xA0;
        r[31] = (i + 1) as u8;
        r
    };

    // Fill the ring exactly.
    for i in 0..ring {
        let ix = env.update_root_ix(&assoc, &curator, &root_at(i));
        env.process(&ix, &[Check::success()]);
    }
    let data = env.get(&assoc).data;
    for i in 0..ring {
        assert!(
            association::is_known_root(&data, &root_at(i)).unwrap(),
            "root {i} must still be accepted while the ring is exactly full"
        );
    }
    assert_eq!(association::update_count(&data).unwrap(), ring as u64);

    // One more publication evicts the OLDEST, not an arbitrary slot.
    let ix = env.update_root_ix(&assoc, &curator, &root_at(ring));
    env.process(&ix, &[Check::success()]);
    let data = env.get(&assoc).data;
    assert!(
        !association::is_known_root(&data, &root_at(0)).unwrap(),
        "the oldest root must be evicted"
    );
    for i in 1..=ring {
        assert!(
            association::is_known_root(&data, &root_at(i)).unwrap(),
            "root {i} must survive the wrap"
        );
    }
}

