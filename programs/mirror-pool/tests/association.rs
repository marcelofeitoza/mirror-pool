#[test]
fn init_association_registers_and_reinit_fails() {
    let mut env = Env::new();
    let authority = Pubkey::new_unique();
    env.fund(authority, SOL);
    let payer = Pubkey::new_unique();
    env.fund(payer, 10 * SOL);
    let pool = build_zk_pool(&mut env, &authority, 10, 5 * SOL);

    let curator = Pubkey::new_unique();
    env.fund(curator, SOL);
    let assoc = register_curator(&mut env, &pool, &curator, &payer);

    let data = env.get(&assoc).data;
    assert_eq!(env.get(&assoc).owner, env.program_id);
    assert_eq!(data.len(), association::LEN);
    assert_eq!(
        association::version(&data).unwrap(),
        association::VERSION_V1
    );
    assert_eq!(association::pool(&data).unwrap(), pool.to_bytes());
    assert_eq!(association::curator(&data).unwrap(), curator.to_bytes());
    assert_eq!(association::update_count(&data).unwrap(), 0);
    // A set with no published root vouches for nothing: every slot is the
    // sentinel and is_known_root rejects it.
    for i in 0..association::ROOT_HISTORY_SIZE {
        assert_eq!(
            association::root_history_entry(&data, i).unwrap(),
            association::EMPTY_SLOT
        );
    }
    assert!(!association::is_known_root(&data, &association::EMPTY_SLOT).unwrap());

    // Re-registering the same (pool, curator) fails closed.
    let ix = env.init_assoc_ix(&assoc, &pool, &curator, &payer);
    env.process(
        &ix,
        &[Check::err(custom(
            MirrorPoolError::AssociationAlreadyInitialized,
        ))],
    );
}

#[test]
fn init_association_is_permissionless_across_curators() {
    // Two independent curators register competing sets over the SAME pool. This
    // is the anti-censorship property: no single curator owns the compliance
    // story for a pool.
    let mut env = Env::new();
    let authority = Pubkey::new_unique();
    env.fund(authority, SOL);
    let payer = Pubkey::new_unique();
    env.fund(payer, 10 * SOL);
    let pool = build_zk_pool(&mut env, &authority, 10, 5 * SOL);

    let curator_a = Pubkey::new_unique();
    let curator_b = Pubkey::new_unique();
    env.fund(curator_a, SOL);
    env.fund(curator_b, SOL);
    let assoc_a = register_curator(&mut env, &pool, &curator_a, &payer);
    let assoc_b = register_curator(&mut env, &pool, &curator_b, &payer);

    assert_ne!(assoc_a, assoc_b, "each curator gets its own set account");
    assert_eq!(
        association::curator(&env.get(&assoc_a).data).unwrap(),
        curator_a.to_bytes()
    );
    assert_eq!(
        association::curator(&env.get(&assoc_b).data).unwrap(),
        curator_b.to_bytes()
    );
}

