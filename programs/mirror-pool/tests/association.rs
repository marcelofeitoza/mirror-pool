//! Integration tests for the OPT-IN association (Privacy-Pools-style) layer.
//!
//! These load the COMPILED SBF program into mollusk's in-process SVM and drive
//! real instructions, so run `cargo build-sbf` first.
//!
//! Coverage:
//!  - INIT_ASSOCIATION registers a curator's set; re-registration fails; a set
//!    over a non-pool account is rejected; a body byte is rejected.
//!  - UPDATE_ASSOCIATION_ROOT publishes into the ring, only for the registered
//!    curator; the all-zero root is refused; the ring wraps and evicts the oldest.
//!  - SETTLE_ZK_ASSOCIATED ACCEPTS the committed association fixture proof and
//!    executes the escrow transfer.
//!  - SETTLE_ZK_ASSOCIATED REJECTS a proof whose association root the curator
//!    never published (AssociationRootNotKnown), one whose root has AGED OUT of
//!    the ring (the "stale root" case), one against a set belonging to a
//!    DIFFERENT pool, one against a forged (non-PDA / non-program-owned) set
//!    account, and one where the on-chain root is known but the PROOF commits to
//!    a different association root (ProofVerificationFailed).
//!  - The two settle paths share ONE spent-set: settling with an association
//!    proof burns the nullifier for the plain path too.
//!  - A membership (4-input) proof cannot satisfy the association instruction.

use std::collections::{HashMap, HashSet};

use mollusk_svm::{
    program::keyed_account_for_system_program,
    result::{Check, InstructionResult},
    Mollusk,
};
use solana_account::Account;
use solana_instruction::{AccountMeta, Instruction};
use solana_program_error::ProgramError;
use solana_pubkey::Pubkey;

use mirror_pool::{
    pda::{ASSOCIATION_SEED, NULLIFIER_SEED, POOL_SEED},
    state::{association, nullifier, pool},
    wire::tag,
    MirrorPoolError,
};

const SOL: u64 = 1_000_000_000;

/// The committed, known-good ASSOCIATION proof + public inputs (generated by
/// `circuits/build_association.sh`). PUBLIC_INPUTS is
/// `[root, nullifierHash, actionHash, epoch, associationRoot]`.
mod fixture {
    include!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../circuits/artifacts/association_proof_fixture.rs"
    ));
}

/// The committed MEMBERSHIP fixture, used only to show a 4-input membership proof
/// cannot satisfy the 5-input association instruction. Only its PROOF_* bytes are
/// needed here (the public inputs come from the association fixture, so the two
/// settle paths are driven at the same nullifier), hence the `dead_code` allow on
/// the generated constants.
#[allow(dead_code)]
mod membership_fixture {
    include!(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../circuits/artifacts/proof_fixture.rs"
    ));
}

/// The fixture's epoch (public signal [3] = 11; see gen_association_fixture.js).
const ZK_EPOCH: u64 = 11;
/// The escrow amount bound into the fixture's actionHash (0.75 SOL).
const ZK_AMOUNT: u64 = 750_000_000;

/// The fresh recipient bound into the fixture's actionHash: bytes 0x21..0x40.
fn zk_recipient() -> Pubkey {
    let mut b = [0u8; 32];
    for (i, x) in b.iter_mut().enumerate() {
        *x = (i + 0x21) as u8;
    }
    Pubkey::new_from_array(b)
}

/// Map a program error code to the `ProgramError` mollusk compares against.
fn custom(e: MirrorPoolError) -> ProgramError {
    ProgramError::Custom(e as u32)
}

/// The circuit's empty-tree root, recomputed on the host with `light-poseidon`
/// (the same Poseidon the `sol_poseidon` syscall is built on).
fn circuit_empty_root() -> [u8; 32] {
    use ark_bn254::Fr;
    use ark_ff::{BigInteger, PrimeField};
    use light_poseidon::{Poseidon, PoseidonHasher};

    let mut z = Fr::from(0u64);
    for _ in 0..mirror_pool::state::merkle::DEPTH {
        let mut h = Poseidon::<Fr>::new_circom(2).unwrap();
        z = h.hash(&[z, z]).unwrap();
    }
    let be = z.into_bigint().to_bytes_be();
    let mut out = [0u8; 32];
    out[32 - be.len()..].copy_from_slice(&be);
    out
}

/// A tiny stateful harness (the same shape `integration.rs` uses).
struct Env {
    mollusk: Mollusk,
    program_id: Pubkey,
    system_id: Pubkey,
    clock_id: Pubkey,
    accounts: HashMap<Pubkey, Account>,
}

impl Env {
    fn new() -> Self {
        std::env::set_var(
            "SBF_OUT_DIR",
            concat!(env!("CARGO_MANIFEST_DIR"), "/target/deploy"),
        );
        let program_id = Pubkey::new_unique();
        let mollusk = Mollusk::new(&program_id, "mirror_pool");
        let system_id = keyed_account_for_system_program().0;
        let clock_id = mollusk.sysvars.keyed_account_for_clock_sysvar().0;
        Env {
            mollusk,
            program_id,
            system_id,
            clock_id,
            accounts: HashMap::new(),
        }
    }

    fn fund(&mut self, key: Pubkey, lamports: u64) {
        self.accounts
            .insert(key, Account::new(lamports, 0, &self.system_id));
    }

    fn get(&self, key: &Pubkey) -> Account {
        self.accounts.get(key).cloned().unwrap_or_default()
    }

    fn warp(&mut self, slot: u64) {
        self.mollusk.warp_to_slot(slot);
    }

    fn accounts_for(&self, ix: &Instruction) -> Vec<(Pubkey, Account)> {
        let mut seen = HashSet::new();
        let mut out = Vec::new();
        for meta in &ix.accounts {
            if !seen.insert(meta.pubkey) {
                continue;
            }
            let account = if meta.pubkey == self.system_id {
                keyed_account_for_system_program().1
            } else if meta.pubkey == self.clock_id {
                self.mollusk.sysvars.keyed_account_for_clock_sysvar().1
            } else {
                self.get(&meta.pubkey)
            };
            out.push((meta.pubkey, account));
        }
        out
    }

    fn process(&mut self, ix: &Instruction, checks: &[Check]) -> InstructionResult {
        let accts = self.accounts_for(ix);
        let result = self
            .mollusk
            .process_and_validate_instruction(ix, &accts, checks);
        for (key, account) in &result.resulting_accounts {
            if *key != self.system_id && *key != self.clock_id {
                self.accounts.insert(*key, account.clone());
            }
        }
        result
    }

    fn pool_pda(&self, authority: &Pubkey) -> Pubkey {
        Pubkey::find_program_address(&[POOL_SEED, authority.as_ref()], &self.program_id).0
    }

    fn assoc_pda(&self, pool: &Pubkey, curator: &Pubkey) -> Pubkey {
        Pubkey::find_program_address(
            &[ASSOCIATION_SEED, pool.as_ref(), curator.as_ref()],
            &self.program_id,
        )
        .0
    }

    fn nf_pda(&self, pool: &Pubkey, epoch_id: u64, nf: &[u8; 32]) -> Pubkey {
        Pubkey::find_program_address(
            &[NULLIFIER_SEED, pool.as_ref(), &epoch_id.to_le_bytes(), nf],
            &self.program_id,
        )
        .0
    }

    fn init_assoc_ix(
        &self,
        assoc: &Pubkey,
        pool: &Pubkey,
        curator: &Pubkey,
        payer: &Pubkey,
    ) -> Instruction {
        Instruction {
            program_id: self.program_id,
            accounts: vec![
                AccountMeta::new(*assoc, false),
                AccountMeta::new_readonly(*pool, false),
                AccountMeta::new_readonly(*curator, true),
                AccountMeta::new(*payer, true),
                AccountMeta::new_readonly(self.system_id, false),
            ],
            data: vec![tag::INIT_ASSOCIATION],
        }
    }

    fn update_root_ix(&self, assoc: &Pubkey, curator: &Pubkey, root: &[u8; 32]) -> Instruction {
        let mut data = Vec::with_capacity(mirror_pool::wire::UPDATE_ASSOCIATION_ROOT_LEN);
        data.push(tag::UPDATE_ASSOCIATION_ROOT);
        data.extend_from_slice(root);
        Instruction {
            program_id: self.program_id,
            accounts: vec![
                AccountMeta::new(*assoc, false),
                AccountMeta::new_readonly(*curator, true),
            ],
            data,
        }
    }

    /// Build a `SettleZkAssociated` instruction from explicit proof bytes, so a
    /// test can substitute a membership proof to show it is rejected.
    #[allow(clippy::too_many_arguments)]
    fn settle_assoc_ix_with_proof(
        &self,
        pool: &Pubkey,
        authority: &Pubkey,
        nf_pda: &Pubkey,
        recipient: &Pubkey,
        assoc: &Pubkey,
        epoch_id: u64,
        amount: u64,
        proof_a: &[u8; 64],
        proof_b: &[u8; 128],
        proof_c: &[u8; 64],
        public_inputs: &[[u8; 32]; 5],
    ) -> Instruction {
        let mut data = Vec::with_capacity(mirror_pool::wire::SETTLE_ZK_ASSOCIATED_LEN);
        data.push(tag::SETTLE_ZK_ASSOCIATED);
        data.extend_from_slice(&epoch_id.to_le_bytes());
        data.extend_from_slice(&amount.to_le_bytes());
        data.extend_from_slice(proof_a);
        data.extend_from_slice(proof_b);
        data.extend_from_slice(proof_c);
        for pi in public_inputs {
            data.extend_from_slice(pi);
        }
        Instruction {
            program_id: self.program_id,
            accounts: vec![
                AccountMeta::new(*pool, false),
                AccountMeta::new(*authority, true),
                AccountMeta::new(*nf_pda, false),
                AccountMeta::new(*recipient, false),
                AccountMeta::new_readonly(self.system_id, false),
                AccountMeta::new_readonly(self.clock_id, false),
                AccountMeta::new_readonly(*assoc, false),
            ],
            data,
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn settle_assoc_ix(
        &self,
        pool: &Pubkey,
        authority: &Pubkey,
        nf_pda: &Pubkey,
        recipient: &Pubkey,
        assoc: &Pubkey,
        epoch_id: u64,
        amount: u64,
        public_inputs: &[[u8; 32]; 5],
    ) -> Instruction {
        self.settle_assoc_ix_with_proof(
            pool,
            authority,
            nf_pda,
            recipient,
            assoc,
            epoch_id,
            amount,
            &fixture::PROOF_A,
            &fixture::PROOF_B,
            &fixture::PROOF_C,
            public_inputs,
        )
    }

    /// The plain `SettleZk` instruction, used only to show the two paths share a
    /// spent-set.
    #[allow(clippy::too_many_arguments)]
    fn settle_zk_ix(
        &self,
        pool: &Pubkey,
        authority: &Pubkey,
        nf_pda: &Pubkey,
        recipient: &Pubkey,
        epoch_id: u64,
        amount: u64,
        public_inputs: &[[u8; 32]; 4],
    ) -> Instruction {
        let mut data = Vec::with_capacity(mirror_pool::wire::SETTLE_ZK_LEN);
        data.push(tag::SETTLE_ZK);
        data.extend_from_slice(&epoch_id.to_le_bytes());
        data.extend_from_slice(&amount.to_le_bytes());
        data.extend_from_slice(&membership_fixture::PROOF_A);
        data.extend_from_slice(&membership_fixture::PROOF_B);
        data.extend_from_slice(&membership_fixture::PROOF_C);
        for pi in public_inputs {
            data.extend_from_slice(pi);
        }
        Instruction {
            program_id: self.program_id,
            accounts: vec![
                AccountMeta::new(*pool, false),
                AccountMeta::new(*authority, true),
                AccountMeta::new(*nf_pda, false),
                AccountMeta::new(*recipient, false),
                AccountMeta::new_readonly(self.system_id, false),
                AccountMeta::new_readonly(self.clock_id, false),
            ],
            data,
        }
    }
}

/// Hand-build an initialized Pool whose recent-root ring already contains the
/// committed association fixture's POOL root (public signal [0]), and fund it.
/// A real deposit sequence cannot reproduce the fixture's exact tree, so the test
/// injects the snapshot - the same technique `integration.rs` uses for SettleZk.
fn build_zk_pool(env: &mut Env, authority: &Pubkey, epoch_slots: u64, lamports: u64) -> Pubkey {
    let pool = env.pool_pda(authority);
    let (_, bump) = Pubkey::find_program_address(&[POOL_SEED, authority.as_ref()], &env.program_id);
    let mut data = vec![0u8; pool::LEN];
    pool::init(
        &mut data,
        epoch_slots,
        2,
        0,
        0,
        &authority.to_bytes(),
        bump,
        &circuit_empty_root(),
    )
    .unwrap();
    pool::record_root_history(&mut data, &fixture::PUBLIC_INPUTS[0]).unwrap();
    assert!(pool::is_known_root(&data, &fixture::PUBLIC_INPUTS[0]).unwrap());
    let mut account = Account::new(lamports, pool::LEN, &env.program_id);
    account.data = data;
    env.accounts.insert(pool, account);
    pool
}

/// Register a curator's association set for `pool` through the real instruction.
fn register_curator(env: &mut Env, pool: &Pubkey, curator: &Pubkey, payer: &Pubkey) -> Pubkey {
    let assoc = env.assoc_pda(pool, curator);
    let ix = env.init_assoc_ix(&assoc, pool, curator, payer);
    env.process(&ix, &[Check::success()]);
    assoc
}

/// A full happy-path setup: pool with the fixture root, a registered curator that
/// has published the fixture's association root, and a funded recipient.
fn setup_associated(env: &mut Env) -> (Pubkey, Pubkey, Pubkey, Pubkey) {
    let authority = Pubkey::new_unique();
    env.fund(authority, SOL); // pays the nullifier PDA rent
    let payer = Pubkey::new_unique();
    env.fund(payer, 10 * SOL);
    let pool = build_zk_pool(env, &authority, 10, 5 * SOL + ZK_AMOUNT);

    let curator = Pubkey::new_unique();
    env.fund(curator, SOL);
    let assoc = register_curator(env, &pool, &curator, &payer);

    // The curator publishes the fixture's association root (public signal [4]).
    let ix = env.update_root_ix(&assoc, &curator, &fixture::PUBLIC_INPUTS[4]);
    env.process(&ix, &[Check::success()]);

    let recipient = zk_recipient();
    env.fund(recipient, 0);
    (authority, pool, curator, assoc)
}

