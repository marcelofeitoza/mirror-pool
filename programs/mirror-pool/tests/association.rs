#[test]
fn update_association_root_publishes_and_only_curator_may() {
    let mut env = Env::new();
    let authority = Pubkey::new_unique();
    env.fund(authority, SOL);
    let payer = Pubkey::new_unique();
    env.fund(payer, 10 * SOL);
    let pool = build_zk_pool(&mut env, &authority, 10, 5 * SOL);
    let curator = Pubkey::new_unique();
    env.fund(curator, SOL);
    let assoc = register_curator(&mut env, &pool, &curator, &payer);

    let root = [9u8; 32];
    let ix = env.update_root_ix(&assoc, &curator, &root);
    env.process(&ix, &[Check::success()]);

    let data = env.get(&assoc).data;
    assert_eq!(association::update_count(&data).unwrap(), 1);
    assert!(association::is_known_root(&data, &root).unwrap());
    assert_eq!(association::root_head(&data).unwrap(), 1);

    // An imposter cannot publish, even though the account is program-owned.
    let imposter = Pubkey::new_unique();
    env.fund(imposter, SOL);
    let ix = env.update_root_ix(&assoc, &imposter, &[8u8; 32]);
    env.process(&ix, &[Check::err(custom(MirrorPoolError::Unauthorized))]);
    assert_eq!(
        association::update_count(&env.get(&assoc).data).unwrap(),
        1,
        "a rejected publish must not bump the counter"
    );
}

