//! Integration tests for the OPT-IN disclosure layer: on-chain viewing keys and
//! sealed disclosure records.
//!
//! These load the COMPILED SBF program into mollusk's in-process SVM and drive
//! real instructions, so run `cargo build-sbf` first.
//!
//! Coverage:
//!  - REGISTER_VIEWING_KEY creates the PDA, binds the signing authority, and
//!    rotates only for that authority; a body byte, a wrong PDA, a foreign signer
//!    and a degenerate key are all rejected.
//!  - PUBLISH_DISCLOSURE accepts a well-formed record and stores the fields it
//!    recomputed, not the ones it was handed.
//!  - PUBLISH_DISCLOSURE REJECTS the two failure modes the rival design has: an
//!    unauthenticated publisher (no recipient signature) and a SQUAT on another
//!    user's settlement (the slot is derived from the signer, so it is not
//!    reachable), plus an unregistered or forged reader, a structurally invalid
//!    sealed blob, an off-denomination amount, a non-pool account, and a second
//!    write to the same record.
//!  - The whole layer is opt-in: SETTLE_ZK settles the committed fixture with no
//!    viewing key and no record anywhere, and the record published for that same
//!    action reproduces, off-chain, the exact nullifier the settle burned.

