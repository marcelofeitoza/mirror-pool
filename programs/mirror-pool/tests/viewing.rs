/// The reader must be a real, registered viewing key sitting at its own PDA. A
/// record that named an unregistered key would be a disclosure to nobody, and a
/// record that trusted a caller-supplied key would let anyone claim any reader.
#[test]
fn publish_disclosure_rejects_an_unregistered_or_forged_reader() {
    let mut env = Env::new();
    let auditor_kp = viewing_keypair(16);
    let (auditor, auditor_viewkey) = env.register_auditor(&auditor_kp.public());
    let pool_authority = Pubkey::new_unique();
    let pool = build_zk_pool(&mut env, &pool_authority, 10, 50 * SOL);
    let recipient = zk_recipient();
    env.fund(recipient, SOL);
    let blob = mirror_core::disclosure::seal(
        &auditor_kp.public(),
        mirror_core::Epoch(ZK_EPOCH),
        &mirror_core::Secret(FIXTURE_SECRET),
    );
    let action_hash = host_action_hash(&recipient, ZK_AMOUNT);
    let record = env.disclosure_pda(&pool, &action_hash, &auditor_kp.public());

    // (a) A never-registered authority: the PDA exists as an address but holds
    // nothing.
    let unregistered = env.viewkey_pda(&Pubkey::new_unique());
    let ix = env.publish_ix(
        &record,
        &pool,
        &recipient,
        true,
        &unregistered,
        &recipient,
        ZK_AMOUNT,
        &blob,
    );
    env.process(
        &ix,
        &[Check::err(custom(MirrorPoolError::ViewingKeyNotInitialized))],
    );

    // (b) A forged, program-owned account that PARSES as a registration but does
    // not sit at the PDA of the authority it names.
    let forged = Pubkey::new_unique();
    let mut data = vec![0u8; viewing_key::LEN];
    viewing_key::init(&mut data, &auditor.to_bytes(), &auditor_kp.public(), 255).unwrap();
    let mut account = Account::new(SOL, viewing_key::LEN, &env.program_id);
    account.data = data;
    env.accounts.insert(forged, account);
    let ix = env.publish_ix(
        &record,
        &pool,
        &recipient,
        true,
        &forged,
        &recipient,
        ZK_AMOUNT,
        &blob,
    );
    env.process(&ix, &[Check::err(custom(MirrorPoolError::InvalidPda))]);

    // (c) The real registration works.
    let ix = env.publish_ix(
        &record,
        &pool,
        &recipient,
        true,
        &auditor_viewkey,
        &recipient,
        ZK_AMOUNT,
        &blob,
    );
    env.process(&ix, &[Check::success()]);
}

/// The stored blob is structurally validated, not accepted as an opaque byte
/// string: its length is fixed by the layout and its ephemeral X25519 key must be
/// canonical and not small-order. The small-order case is the one that matters -
/// it is where a user believes they sealed to one reader and in fact sealed to
/// everybody.
#[test]
fn publish_disclosure_rejects_a_structurally_invalid_blob() {
    let mut env = Env::new();
    let auditor_kp = viewing_keypair(17);
    let (_auditor, auditor_viewkey) = env.register_auditor(&auditor_kp.public());
    let pool_authority = Pubkey::new_unique();
    let pool = build_zk_pool(&mut env, &pool_authority, 10, 50 * SOL);
    let recipient = zk_recipient();
    env.fund(recipient, SOL);
    let good = mirror_core::disclosure::seal(
        &auditor_kp.public(),
        mirror_core::Epoch(ZK_EPOCH),
        &mirror_core::Secret(FIXTURE_SECRET),
    );
    let action_hash = host_action_hash(&recipient, ZK_AMOUNT);
    let record = env.disclosure_pda(&pool, &action_hash, &auditor_kp.public());

    // (a) An all-zero (order-4) ephemeral key: the ECDH output would not depend
    // on the reader's secret at all.
    let mut degenerate = good.clone();
    degenerate[..32].copy_from_slice(&[0u8; 32]);
    let ix = env.publish_ix(
        &record,
        &pool,
        &recipient,
        true,
        &auditor_viewkey,
        &recipient,
        ZK_AMOUNT,
        &degenerate,
    );
    env.process(
        &ix,
        &[Check::err(custom(MirrorPoolError::InvalidDisclosureBlob))],
    );

    // (b) A non-canonical ephemeral encoding (high bit set).
    let mut aliased = good.clone();
    aliased[31] |= 0x80;
    let ix = env.publish_ix(
        &record,
        &pool,
        &recipient,
        true,
        &auditor_viewkey,
        &recipient,
        ZK_AMOUNT,
        &aliased,
    );
    env.process(
        &ix,
        &[Check::err(custom(MirrorPoolError::InvalidDisclosureBlob))],
    );

    // (c) A short and a long blob are malformed on shape alone.
    for body in [&good[..99], &good[..]] {
        let mut ix = env.publish_ix(
            &record,
            &pool,
            &recipient,
            true,
            &auditor_viewkey,
            &recipient,
            ZK_AMOUNT,
            body,
        );
        if body.len() == good.len() {
            ix.data.push(0);
        }
        env.process(
            &ix,
            &[Check::err(custom(MirrorPoolError::MalformedInstruction))],
        );
    }
    assert!(env.get(&record).data.is_empty());
}

/// A record is write-once: its publisher cannot come back and rewrite the
/// evidence.
#[test]
fn publish_disclosure_is_write_once() {
    let mut env = Env::new();
    let auditor_kp = viewing_keypair(18);
    let (_auditor, auditor_viewkey) = env.register_auditor(&auditor_kp.public());
    let pool_authority = Pubkey::new_unique();
    let pool = build_zk_pool(&mut env, &pool_authority, 10, 50 * SOL);
    let recipient = zk_recipient();
    env.fund(recipient, SOL);
    let first = mirror_core::disclosure::seal(
        &auditor_kp.public(),
        mirror_core::Epoch(ZK_EPOCH),
        &mirror_core::Secret(FIXTURE_SECRET),
    );
    let action_hash = host_action_hash(&recipient, ZK_AMOUNT);
    let record = env.disclosure_pda(&pool, &action_hash, &auditor_kp.public());

    let ix = env.publish_ix(
        &record,
        &pool,
        &recipient,
        true,
        &auditor_viewkey,
        &recipient,
        ZK_AMOUNT,
        &first,
    );
    env.process(&ix, &[Check::success()]);

    let second = mirror_core::disclosure::seal(
        &auditor_kp.public(),
        mirror_core::Epoch(ZK_EPOCH),
        &mirror_core::Secret([7u8; 32]),
    );
    let ix = env.publish_ix(
        &record,
        &pool,
        &recipient,
        true,
        &auditor_viewkey,
        &recipient,
        ZK_AMOUNT,
        &second,
    );
    env.process(
        &ix,
        &[Check::err(custom(
            MirrorPoolError::DisclosureAlreadyInitialized,
        ))],
    );
    assert_eq!(
        disclosure::blob(&env.get(&record).data).unwrap(),
        &first[..],
        "the original record must survive"
    );
}

