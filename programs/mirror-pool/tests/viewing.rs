/// The fixture's epoch (public signal [3] = 7; see gen_fixture.js).
const ZK_EPOCH: u64 = 7;
/// The escrow amount bound into the fixture's actionHash.
const ZK_AMOUNT: u64 = 250_000_000;

/// The fixture's note secret, `111122223333444455556666777788889999` as a
/// canonical big-endian BN254 scalar (see `circuits/gen_fixture.js`). This is
/// what a real user would seal to their auditor, and disclosing it here lets the
/// test check that the auditor recomputes the SAME nullifier the on-chain settle
/// burns two lines later.
const FIXTURE_SECRET: [u8; 32] = [
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x15, 0x66, 0xbf, 0xa4, 0x9d, 0x36, 0x82, 0x8e, 0x17, 0xeb, 0x19, 0xd1, 0x9a, 0x3b, 0x8f,
];

/// The fresh recipient bound into the fixture's actionHash: bytes 0x01..0x20.
fn zk_recipient() -> Pubkey {
    let mut b = [0u8; 32];
    for (i, x) in b.iter_mut().enumerate() {
        *x = (i + 1) as u8;
    }
    Pubkey::new_from_array(b)
}

/// Map a program error code to the `ProgramError` mollusk compares against.
fn custom(e: MirrorPoolError) -> ProgramError {
    ProgramError::Custom(e as u32)
}

/// The circuit's empty-tree root, recomputed on the host with `light-poseidon`.
fn circuit_empty_root() -> [u8; 32] {
    use ark_bn254::Fr;
    use ark_ff::{BigInteger, PrimeField};
    use light_poseidon::{Poseidon, PoseidonHasher};

    let mut z = Fr::from(0u64);
    for _ in 0..mirror_pool::state::merkle::DEPTH {
        let mut h = Poseidon::<Fr>::new_circom(2).unwrap();
        z = h.hash(&[z, z]).unwrap();
    }
    let be = z.into_bigint().to_bytes_be();
    let mut out = [0u8; 32];
    out[32 - be.len()..].copy_from_slice(&be);
    out
}

/// A deterministic 32-byte value from one seed byte (test key material).
fn bytes(seed: u8) -> [u8; 32] {
    let mut b = [0u8; 32];
    for (i, x) in b.iter_mut().enumerate() {
        *x = seed.wrapping_add(i as u8).wrapping_mul(31).wrapping_add(7);
    }
    b
}

/// A real X25519 viewing keypair, built through the host crate the CLI uses.
fn viewing_keypair(seed: u8) -> mirror_core::encrypted_note::ViewingKeypair {
    mirror_core::encrypted_note::ViewingKeypair::from_secret(bytes(seed))
}

/// A tiny stateful harness (the same shape `integration.rs` uses).
struct Env {
    mollusk: Mollusk,
    program_id: Pubkey,
    system_id: Pubkey,
    clock_id: Pubkey,
    accounts: HashMap<Pubkey, Account>,
}

impl Env {
    fn new() -> Self {
        std::env::set_var(
            "SBF_OUT_DIR",
            concat!(env!("CARGO_MANIFEST_DIR"), "/target/deploy"),
        );
        let program_id = Pubkey::new_unique();
        let mollusk = Mollusk::new(&program_id, "mirror_pool");
        let system_id = keyed_account_for_system_program().0;
        let clock_id = mollusk.sysvars.keyed_account_for_clock_sysvar().0;
        Env {
            mollusk,
            program_id,
            system_id,
            clock_id,
            accounts: HashMap::new(),
        }
    }

    fn fund(&mut self, key: Pubkey, lamports: u64) {
        self.accounts
            .insert(key, Account::new(lamports, 0, &self.system_id));
    }

    fn get(&self, key: &Pubkey) -> Account {
        self.accounts.get(key).cloned().unwrap_or_default()
    }

    fn warp(&mut self, slot: u64) {
        self.mollusk.warp_to_slot(slot);
    }

    fn accounts_for(&self, ix: &Instruction) -> Vec<(Pubkey, Account)> {
        let mut seen = HashSet::new();
        let mut out = Vec::new();
        for meta in &ix.accounts {
            if !seen.insert(meta.pubkey) {
                continue;
            }
            let account = if meta.pubkey == self.system_id {
                keyed_account_for_system_program().1
            } else if meta.pubkey == self.clock_id {
                self.mollusk.sysvars.keyed_account_for_clock_sysvar().1
            } else {
                self.get(&meta.pubkey)
            };
            out.push((meta.pubkey, account));
        }
        out
    }

    fn process(&mut self, ix: &Instruction, checks: &[Check]) -> InstructionResult {
        let accts = self.accounts_for(ix);
        let result = self
            .mollusk
            .process_and_validate_instruction(ix, &accts, checks);
        for (key, account) in &result.resulting_accounts {
            if *key != self.system_id && *key != self.clock_id {
                self.accounts.insert(*key, account.clone());
            }
        }
        result
    }

    fn pool_pda(&self, authority: &Pubkey) -> Pubkey {
        Pubkey::find_program_address(&[POOL_SEED, authority.as_ref()], &self.program_id).0
    }

    fn viewkey_pda(&self, authority: &Pubkey) -> Pubkey {
        Pubkey::find_program_address(&[VIEWING_KEY_SEED, authority.as_ref()], &self.program_id).0
    }

    fn disclosure_pda(
        &self,
        pool: &Pubkey,
        action_hash: &[u8; 32],
        view_pub: &[u8; 32],
    ) -> Pubkey {
        Pubkey::find_program_address(
            &[DISCLOSURE_SEED, pool.as_ref(), action_hash, view_pub],
            &self.program_id,
        )
        .0
    }

    fn nf_pda(&self, pool: &Pubkey, epoch_id: u64, nf: &[u8; 32]) -> Pubkey {
        Pubkey::find_program_address(
            &[NULLIFIER_SEED, pool.as_ref(), &epoch_id.to_le_bytes(), nf],
            &self.program_id,
        )
        .0
    }

    fn register_ix(
        &self,
        viewkey: &Pubkey,
        authority: &Pubkey,
        payer: &Pubkey,
        view_pub: &[u8; 32],
    ) -> Instruction {
        let mut data = Vec::with_capacity(mirror_pool::wire::REGISTER_VIEWING_KEY_LEN);
        data.push(tag::REGISTER_VIEWING_KEY);
        data.extend_from_slice(view_pub);
        Instruction {
            program_id: self.program_id,
            accounts: vec![
                AccountMeta::new(*viewkey, false),
                AccountMeta::new_readonly(*authority, true),
                AccountMeta::new(*payer, true),
                AccountMeta::new_readonly(self.system_id, false),
            ],
            data,
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn publish_ix(
        &self,
        record: &Pubkey,
        pool: &Pubkey,
        recipient: &Pubkey,
        recipient_signs: bool,
        auditor_viewkey: &Pubkey,
        payer: &Pubkey,
        amount: u64,
        blob: &[u8],
    ) -> Instruction {
        let mut data = Vec::with_capacity(mirror_pool::wire::PUBLISH_DISCLOSURE_LEN);
        data.push(tag::PUBLISH_DISCLOSURE);
        data.extend_from_slice(&amount.to_le_bytes());
        data.extend_from_slice(blob);
        Instruction {
            program_id: self.program_id,
            accounts: vec![
                AccountMeta::new(*record, false),
                AccountMeta::new_readonly(*pool, false),
                AccountMeta::new_readonly(*recipient, recipient_signs),
                AccountMeta::new_readonly(*auditor_viewkey, false),
                AccountMeta::new(*payer, true),
                AccountMeta::new_readonly(self.system_id, false),
            ],
            data,
        }
    }

    fn settle_zk_ix(
        &self,
        pool: &Pubkey,
        authority: &Pubkey,
        nf_pda: &Pubkey,
        recipient: &Pubkey,
    ) -> Instruction {
        let mut data = Vec::with_capacity(mirror_pool::wire::SETTLE_ZK_LEN);
        data.push(tag::SETTLE_ZK);
        data.extend_from_slice(&ZK_EPOCH.to_le_bytes());
        data.extend_from_slice(&ZK_AMOUNT.to_le_bytes());
        data.extend_from_slice(&fixture::PROOF_A);
        data.extend_from_slice(&fixture::PROOF_B);
        data.extend_from_slice(&fixture::PROOF_C);
        for pi in fixture::PUBLIC_INPUTS.iter() {
            data.extend_from_slice(pi);
        }
        Instruction {
            program_id: self.program_id,
            accounts: vec![
                AccountMeta::new(*pool, false),
                AccountMeta::new(*authority, true),
                AccountMeta::new(*nf_pda, false),
                AccountMeta::new(*recipient, false),
                AccountMeta::new_readonly(self.system_id, false),
                AccountMeta::new_readonly(self.clock_id, false),
                AccountMeta::new_readonly(
                    vk_fixture::vk_registry_pda(&self.program_id, mirror_pool::wire::CIRCUIT_MEMBERSHIP),
                    false,
                ),
            ],
            data,
        }
    }

    /// Install a circuit's pinned verifying key through the REAL `INIT_VK`.
    fn install_vk(&mut self, circuit_id: u8) -> Pubkey {
        let payer = Pubkey::new_unique();
        self.fund(payer, SOL);
        let vk = vk_fixture::canonical_vk(circuit_id);
        let ix = vk_fixture::init_vk_ix(&self.program_id, &self.system_id, &payer, circuit_id, &vk);
        self.process(&ix, &[Check::success()]);
        vk_fixture::vk_registry_pda(&self.program_id, circuit_id)
    }

    /// Register a viewing key for a fresh authority and return
    /// `(authority, viewkey_pda)`.
    fn register_auditor(&mut self, view_pub: &[u8; 32]) -> (Pubkey, Pubkey) {
        let authority = Pubkey::new_unique();
        self.fund(authority, SOL);
        let viewkey = self.viewkey_pda(&authority);
        let ix = self.register_ix(&viewkey, &authority, &authority, view_pub);
        self.process(&ix, &[Check::success()]);
        (authority, viewkey)
    }
}

/// Hand-build an initialized Pool whose recent-root ring already contains the
/// committed fixture's root, and fund it. A real deposit sequence cannot
/// reproduce the fixture's exact tree, so the test injects the snapshot - the
/// same technique `integration.rs` uses for SettleZk.
fn build_zk_pool(env: &mut Env, authority: &Pubkey, epoch_slots: u64, lamports: u64) -> Pubkey {
    let pool = env.pool_pda(authority);
    let (_, bump) = Pubkey::find_program_address(&[POOL_SEED, authority.as_ref()], &env.program_id);
    let mut data = vec![0u8; pool::LEN];
    pool::init(
        &mut data,
        epoch_slots,
        2,
        0,
        0,
        ZK_AMOUNT,
        &authority.to_bytes(),
        bump,
        &circuit_empty_root(),
    )
    .unwrap();
    pool::record_root_history(&mut data, &fixture::PUBLIC_INPUTS[0]).unwrap();
    let mut account = Account::new(lamports, pool::LEN, &env.program_id);
    account.data = data;
    env.accounts.insert(pool, account);
    pool
}

/// The `action_hash` the program will recompute for `(recipient, amount)`,
/// derived here with the HOST implementation so the test also pins that the two
/// agree.
fn host_action_hash(recipient: &Pubkey, amount: u64) -> [u8; 32] {
    mirror_core::transfer_action_hash(&recipient.to_bytes(), amount)
}

