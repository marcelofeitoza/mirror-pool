/// A well-formed record lands, and every field the account keeps is one the
/// PROGRAM derived: the action hash it recomputed from the signing recipient,
/// and the auditor identity + key it read out of the registry account.
#[test]
fn publish_disclosure_stores_what_the_program_recomputed() {
    let mut env = Env::new();
    let auditor_kp = viewing_keypair(10);
    let (auditor, auditor_viewkey) = env.register_auditor(&auditor_kp.public());

    let pool_authority = Pubkey::new_unique();
    let pool = build_zk_pool(&mut env, &pool_authority, 10, 50 * SOL);
    let recipient = zk_recipient();
    env.fund(recipient, SOL);

    let blob = mirror_core::disclosure::seal(
        &auditor_kp.public(),
        mirror_core::Epoch(ZK_EPOCH),
        &mirror_core::Secret(FIXTURE_SECRET),
    );
    let action_hash = host_action_hash(&recipient, ZK_AMOUNT);
    let record = env.disclosure_pda(&pool, &action_hash, &auditor_kp.public());

    let ix = env.publish_ix(
        &record,
        &pool,
        &recipient,
        true,
        &auditor_viewkey,
        &recipient,
        ZK_AMOUNT,
        &blob,
    );
    env.process(&ix, &[Check::success()]);

    let data = env.get(&record).data;
    assert_eq!(data.len(), disclosure::LEN);
    assert!(disclosure::is_initialized(&data).unwrap());
    assert_eq!(disclosure::pool(&data).unwrap(), pool.to_bytes());
    assert_eq!(disclosure::recipient(&data).unwrap(), recipient.to_bytes());
    assert_eq!(disclosure::auditor(&data).unwrap(), auditor.to_bytes());
    assert_eq!(
        disclosure::auditor_view_pub(&data).unwrap(),
        auditor_kp.public()
    );
    assert_eq!(disclosure::amount(&data).unwrap(), ZK_AMOUNT);
    assert_eq!(disclosure::blob(&data).unwrap(), &blob[..]);

    // The on-chain Poseidon recomputation agrees with the host's, and with the
    // committed fixture's actionHash public input: this record is about a
    // statement the settle path really can verify.
    assert_eq!(disclosure::action_hash(&data).unwrap(), action_hash);
    assert_eq!(
        disclosure::action_hash(&data).unwrap(),
        fixture::PUBLIC_INPUTS[2],
        "the recomputed action hash must equal the proof's actionHash"
    );

    // And the reader - and only the reader - can open it.
    let opened = mirror_core::disclosure::open(&auditor_kp.to_secret_bytes(), &blob)
        .expect("the auditor must open their own record");
    let stranger = viewing_keypair(11);
    assert!(mirror_core::disclosure::open(&stranger.to_secret_bytes(), &blob).is_none());
    let action = mirror_core::disclosure::derive_action(&opened, &action_hash);
    assert_eq!(
        action.nullifier.0,
        fixture::PUBLIC_INPUTS[1],
        "the disclosure must reproduce the settlement's nullifier hash"
    );
}

/// The publisher must SIGN. Without the recipient's signature there is nothing
/// tying the record to the settlement it claims, which is exactly the hole in a
/// design where any payer may register any commitment.
#[test]
fn publish_disclosure_requires_the_recipient_signature() {
    let mut env = Env::new();
    let auditor_kp = viewing_keypair(12);
    let (_auditor, auditor_viewkey) = env.register_auditor(&auditor_kp.public());
    let pool_authority = Pubkey::new_unique();
    let pool = build_zk_pool(&mut env, &pool_authority, 10, 50 * SOL);
    let recipient = zk_recipient();
    let payer = Pubkey::new_unique();
    env.fund(payer, SOL);

    let blob = mirror_core::disclosure::seal(
        &auditor_kp.public(),
        mirror_core::Epoch(ZK_EPOCH),
        &mirror_core::Secret(FIXTURE_SECRET),
    );
    let action_hash = host_action_hash(&recipient, ZK_AMOUNT);
    let record = env.disclosure_pda(&pool, &action_hash, &auditor_kp.public());

    let ix = env.publish_ix(
        &record,
        &pool,
        &recipient,
        false, // recipient does not sign
        &auditor_viewkey,
        &payer,
        ZK_AMOUNT,
        &blob,
    );
    env.process(
        &ix,
        &[Check::err(ProgramError::MissingRequiredSignature)],
    );
    assert!(env.get(&record).data.is_empty());
}

/// The squat test. An attacker who has read the chain knows the victim's
/// settlement recipient and amount, so they know the record's address - and
/// still cannot write it, because the address is derived from the SIGNER. When
/// they sign for themselves the derivation lands on THEIR slot, not the
/// victim's, so the victim's record is untouched and still available.
#[test]
fn publish_disclosure_cannot_squat_another_recipients_settlement() {
    let mut env = Env::new();
    let auditor_kp = viewing_keypair(13);
    let (_auditor, auditor_viewkey) = env.register_auditor(&auditor_kp.public());
    let pool_authority = Pubkey::new_unique();
    let pool = build_zk_pool(&mut env, &pool_authority, 10, 50 * SOL);

    let victim = zk_recipient();
    env.fund(victim, SOL);
    let attacker = Pubkey::new_unique();
    env.fund(attacker, SOL);

    let victim_action = host_action_hash(&victim, ZK_AMOUNT);
    let victim_record = env.disclosure_pda(&pool, &victim_action, &auditor_kp.public());
    let junk = mirror_core::disclosure::seal(
        &auditor_kp.public(),
        mirror_core::Epoch(ZK_EPOCH),
        &mirror_core::Secret([9u8; 32]),
    );

    // (a) The attacker signs for themselves and aims at the victim's slot.
    let ix = env.publish_ix(
        &victim_record,
        &pool,
        &attacker,
        true,
        &auditor_viewkey,
        &attacker,
        ZK_AMOUNT,
        &junk,
    );
    env.process(&ix, &[Check::err(custom(MirrorPoolError::InvalidPda))]);

    // (b) The attacker names the victim as recipient without their signature.
    let ix = env.publish_ix(
        &victim_record,
        &pool,
        &victim,
        false,
        &auditor_viewkey,
        &attacker,
        ZK_AMOUNT,
        &junk,
    );
    env.process(
        &ix,
        &[Check::err(ProgramError::MissingRequiredSignature)],
    );
    assert!(
        env.get(&victim_record).data.is_empty(),
        "the victim's slot must still be free"
    );

    // (c) The attacker CAN publish under their own address. That record is about
    // a settlement to themselves and occupies nobody else's slot.
    let attacker_action = host_action_hash(&attacker, ZK_AMOUNT);
    let attacker_record = env.disclosure_pda(&pool, &attacker_action, &auditor_kp.public());
    let ix = env.publish_ix(
        &attacker_record,
        &pool,
        &attacker,
        true,
        &auditor_viewkey,
        &attacker,
        ZK_AMOUNT,
        &junk,
    );
    env.process(&ix, &[Check::success()]);
    assert_ne!(attacker_record, victim_record);

    // (d) And the victim can still publish theirs.
    let blob = mirror_core::disclosure::seal(
        &auditor_kp.public(),
        mirror_core::Epoch(ZK_EPOCH),
        &mirror_core::Secret(FIXTURE_SECRET),
    );
    let ix = env.publish_ix(
        &victim_record,
        &pool,
        &victim,
        true,
        &auditor_viewkey,
        &victim,
        ZK_AMOUNT,
        &blob,
    );
    env.process(&ix, &[Check::success()]);
    assert_eq!(
        disclosure::recipient(&env.get(&victim_record).data).unwrap(),
        victim.to_bytes()
    );
}

