/// The directory works: a signer publishes a key under their own address, and
/// the account records the authority the runtime saw rather than anything the
/// caller could name.
#[test]
fn register_viewing_key_binds_the_signing_authority() {
    let mut env = Env::new();
    let authority = Pubkey::new_unique();
    env.fund(authority, SOL);
    let viewkey = env.viewkey_pda(&authority);
    let view_pub = viewing_keypair(1).public();

    let ix = env.register_ix(&viewkey, &authority, &authority, &view_pub);
    env.process(&ix, &[Check::success()]);

    let data = env.get(&viewkey).data;
    assert_eq!(data.len(), viewing_key::LEN);
    assert!(viewing_key::is_initialized(&data).unwrap());
    assert_eq!(viewing_key::authority(&data).unwrap(), authority.to_bytes());
    assert_eq!(viewing_key::viewing_pub(&data).unwrap(), view_pub);
    assert_eq!(viewing_key::rotation_count(&data).unwrap(), 0);
    assert_eq!(env.get(&viewkey).owner, env.program_id);
}

/// Rotation is allowed for the owner and only the owner. The rotated key lands
/// at the SAME account, so nothing an old record points at is disturbed (records
/// are keyed by the key, not by the authority).
#[test]
fn register_viewing_key_rotates_only_for_its_own_authority() {
    let mut env = Env::new();
    let authority = Pubkey::new_unique();
    let stranger = Pubkey::new_unique();
    env.fund(authority, SOL);
    env.fund(stranger, SOL);
    let viewkey = env.viewkey_pda(&authority);

    let first = viewing_keypair(2).public();
    let ix = env.register_ix(&viewkey, &authority, &authority, &first);
    env.process(&ix, &[Check::success()]);

    // The owner rotates.
    let second = viewing_keypair(3).public();
    let ix = env.register_ix(&viewkey, &authority, &authority, &second);
    env.process(&ix, &[Check::success()]);
    let data = env.get(&viewkey).data;
    assert_eq!(viewing_key::viewing_pub(&data).unwrap(), second);
    assert_eq!(viewing_key::rotation_count(&data).unwrap(), 1);

    // A stranger signing for the SAME account cannot: the account is not the PDA
    // of their address, so the derivation fails before anything is written.
    let hostile = viewing_keypair(4).public();
    let ix = env.register_ix(&viewkey, &stranger, &stranger, &hostile);
    env.process(&ix, &[Check::err(custom(MirrorPoolError::InvalidPda))]);
    let data = env.get(&viewkey).data;
    assert_eq!(
        viewing_key::viewing_pub(&data).unwrap(),
        second,
        "a foreign signer must not overwrite a registration"
    );
}

/// The anti-squat property, stated as a test: a registration can only ever land
/// under the address that signed it, so there is no slot for anyone else to
/// take. The stranger here tries to occupy the victim's directory entry BEFORE
/// the victim ever registers - the first-come-first-served attack the rival
/// design admits - and cannot derive the address.
#[test]
fn register_viewing_key_cannot_squat_another_address() {
    let mut env = Env::new();
    let victim = Pubkey::new_unique();
    let squatter = Pubkey::new_unique();
    env.fund(victim, SOL);
    env.fund(squatter, SOL);
    let victim_slot = env.viewkey_pda(&victim);

    let ix = env.register_ix(&victim_slot, &squatter, &squatter, &viewing_keypair(5).public());
    env.process(&ix, &[Check::err(custom(MirrorPoolError::InvalidPda))]);
    assert!(
        env.get(&victim_slot).data.is_empty(),
        "the victim's slot must still be empty"
    );

    // And the victim can still take their own slot afterwards.
    let mine = viewing_keypair(6).public();
    let ix = env.register_ix(&victim_slot, &victim, &victim, &mine);
    env.process(&ix, &[Check::success()]);
    assert_eq!(
        viewing_key::viewing_pub(&env.get(&victim_slot).data).unwrap(),
        mine
    );
}

/// Degenerate keys are refused: small-order points (whose ECDH output is
/// independent of the peer's secret, so anything sealed to them is public) and
/// non-canonical encodings (which would alias to a second PDA for one key).
#[test]
fn register_viewing_key_rejects_degenerate_keys() {
    let mut env = Env::new();
    let authority = Pubkey::new_unique();
    env.fund(authority, SOL);
    let viewkey = env.viewkey_pda(&authority);

    let mut bad_keys: Vec<[u8; 32]> = vec![
        // The identity / order-1 / order-2 / order-8 points.
        [0u8; 32],
        {
            let mut k = [0u8; 32];
            k[0] = 1;
            k
        },
        {
            let mut k = [0xffu8; 32];
            k[0] = 0xec;
            k[31] = 0x7f;
            k
        },
    ];
    // Non-canonical: high bit set, and p itself.
    let mut high_bit = viewing_keypair(7).public();
    high_bit[31] |= 0x80;
    bad_keys.push(high_bit);
    let mut p = [0xffu8; 32];
    p[0] = 0xed;
    p[31] = 0x7f;
    bad_keys.push(p);

    for key in &bad_keys {
        let ix = env.register_ix(&viewkey, &authority, &authority, key);
        env.process(&ix, &[Check::err(custom(MirrorPoolError::InvalidViewingKey))]);
    }
    assert!(env.get(&viewkey).data.is_empty());

    // A real key from the same generator the CLI uses is accepted.
    let good = viewing_keypair(7).public();
    let ix = env.register_ix(&viewkey, &authority, &authority, &good);
    env.process(&ix, &[Check::success()]);
}

/// Fail closed on shape: this instruction's body is exactly the key.
#[test]
fn register_viewing_key_rejects_a_malformed_body() {
    let mut env = Env::new();
    let authority = Pubkey::new_unique();
    env.fund(authority, SOL);
    let viewkey = env.viewkey_pda(&authority);
    let view_pub = viewing_keypair(8).public();

    for extra in [0usize, 2] {
        let mut ix = env.register_ix(&viewkey, &authority, &authority, &view_pub);
        if extra == 0 {
            ix.data.pop();
        } else {
            ix.data.extend_from_slice(&[0u8; 2]);
        }
        env.process(
            &ix,
            &[Check::err(custom(MirrorPoolError::MalformedInstruction))],
        );
    }
}

