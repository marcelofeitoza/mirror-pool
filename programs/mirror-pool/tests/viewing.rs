/// The whole point of "opt-in". A settlement runs to completion with no viewing
/// key registered anywhere and no disclosure record in existence: SETTLE_ZK never
/// reads either account. The second half of the test then publishes the record
/// for that same action and shows the reader recomputes exactly the nullifier the
/// settle burned - the disclosure is true, and it was never required.
#[test]
fn settling_needs_no_viewing_key_and_no_record() {
    let mut env = Env::new();
    env.install_vk(mirror_pool::wire::CIRCUIT_MEMBERSHIP);

    let authority = Pubkey::new_unique();
    env.fund(authority, SOL);
    let pool = build_zk_pool(&mut env, &authority, 10, 50 * SOL);
    let recipient = zk_recipient();
    env.fund(recipient, 0);
    env.warp(((ZK_EPOCH + 1) * 10) + 1);

    let nf = env.nf_pda(&pool, ZK_EPOCH, &fixture::PUBLIC_INPUTS[1]);
    let ix = env.settle_zk_ix(&pool, &authority, &nf, &recipient);
    env.process(&ix, &[Check::success()]);
    assert_eq!(
        env.get(&recipient).lamports,
        ZK_AMOUNT,
        "the settle must pay the bound recipient with no disclosure anywhere"
    );

    // Now the user discloses that same action to an auditor they chose.
    let auditor_kp = viewing_keypair(20);
    let (_auditor, auditor_viewkey) = env.register_auditor(&auditor_kp.public());
    let blob = mirror_core::disclosure::seal(
        &auditor_kp.public(),
        mirror_core::Epoch(ZK_EPOCH),
        &mirror_core::Secret(FIXTURE_SECRET),
    );
    let action_hash = host_action_hash(&recipient, ZK_AMOUNT);
    let record = env.disclosure_pda(&pool, &action_hash, &auditor_kp.public());
    let payer = Pubkey::new_unique();
    env.fund(payer, SOL);
    let ix = env.publish_ix(
        &record,
        &pool,
        &recipient,
        true,
        &auditor_viewkey,
        &payer,
        ZK_AMOUNT,
        &blob,
    );
    env.process(&ix, &[Check::success()]);

    // The reader opens it and lands on the settlement that just happened.
    let stored = env.get(&record).data;
    let opened = mirror_core::disclosure::open(
        &auditor_kp.to_secret_bytes(),
        disclosure::blob(&stored).unwrap(),
    )
    .expect("the auditor must open the record");
    let action =
        mirror_core::disclosure::derive_action(&opened, &disclosure::action_hash(&stored).unwrap());
    assert_eq!(action.nullifier.0, fixture::PUBLIC_INPUTS[1]);
    let disclosed_nf = env.nf_pda(&pool, action.epoch.0, &action.nullifier.0);
    assert_eq!(
        disclosed_nf, nf,
        "the disclosed nullifier must derive the PDA the settle created"
    );
    assert!(
        !env.get(&disclosed_nf).data.is_empty(),
        "and that PDA must exist on-chain, which is how the reader confirms it settled"
    );
}

/// The mirrored X25519 structural test really is a mirror: the program's copy and
/// `mirror_core`'s agree on every vector that matters, so the CLI can refuse
/// locally exactly what the chain would refuse.
#[test]
fn viewing_key_validation_mirrors_mirror_core() {
    let mut vectors: Vec<[u8; 32]> = Vec::new();
    for seed in 0..8u8 {
        vectors.push(viewing_keypair(seed).public());
        vectors.push(bytes(seed));
    }
    // Degenerate cases.
    vectors.push([0u8; 32]);
    let mut one = [0u8; 32];
    one[0] = 1;
    vectors.push(one);
    let mut p = [0xffu8; 32];
    p[0] = 0xed;
    p[31] = 0x7f;
    vectors.push(p);
    let mut p_minus_1 = p;
    p_minus_1[0] = 0xec;
    vectors.push(p_minus_1);
    let mut p_plus_1 = p;
    p_plus_1[0] = 0xee;
    vectors.push(p_plus_1);
    let mut high = viewing_keypair(1).public();
    high[31] |= 0x80;
    vectors.push(high);

    for v in &vectors {
        assert_eq!(
            viewing_key::is_acceptable_viewing_pub(v),
            mirror_core::encrypted_note::is_acceptable_x25519_pubkey(v),
            "the program and mirror-core must agree on {v:?}"
        );
    }

    // And the disclosure wire sizes are mirrors too.
    assert_eq!(
        mirror_pool::wire::REGISTER_VIEWING_KEY_LEN,
        mirror_core::wire::REGISTER_VIEWING_KEY_LEN
    );
    assert_eq!(
        mirror_pool::wire::PUBLISH_DISCLOSURE_LEN,
        mirror_core::wire::PUBLISH_DISCLOSURE_LEN
    );
    assert_eq!(
        mirror_pool::wire::DISCLOSURE_BLOB_LEN,
        mirror_core::wire::DISCLOSURE_BLOB_LEN
    );
    assert_eq!(tag::REGISTER_VIEWING_KEY, mirror_core::wire::tag::REGISTER_VIEWING_KEY);
    assert_eq!(tag::PUBLISH_DISCLOSURE, mirror_core::wire::tag::PUBLISH_DISCLOSURE);
    assert_eq!(VIEWING_KEY_SEED, mirror_core::wire::VIEWING_KEY_SEED);
    assert_eq!(DISCLOSURE_SEED, mirror_core::wire::DISCLOSURE_SEED);
}
